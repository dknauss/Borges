#!/usr/bin/env node
/**
 * Builds the demo-page step of every Playground demo blueprint.
 *
 * The demo page is defined once, in playground/demo-content.json (samples,
 * feature notes, example bibliographies) and playground/demo-content.php (the
 * script that writes it). Playground blueprints cannot load repository files,
 * so this inlines both into each blueprint's runPHP step.
 *
 *   npm run playground:build          rewrite the blueprints
 *   npm run playground:build -- --check  fail if any blueprint is stale
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');

const RELEASE_INTRO =
	'<strong>Welcome to Borges Bibliography Builder.</strong> This Playground runs the latest release. It is a sandbox: nothing here is kept after you close the tab.';

const DEMO_BLUEPRINTS = [
	{ file: 'playground/blueprint.json', intro: RELEASE_INTRO },
	{
		file: 'playground/blueprint-main.json',
		intro: '<strong>Welcome to the Borges Bibliography Builder development build.</strong> This Playground runs the current <code>main</code> branch, not a stable release. It is a sandbox: nothing here is kept after you close the tab.',
	},
	{ file: '.wordpress-org/blueprints/blueprint.json', intro: RELEASE_INTRO },
];

function phpSingleQuoted(value) {
	return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

/**
 * The runPHP code for one blueprint.
 *
 * @param {string} intro Lead paragraph HTML.
 * @return {string} PHP source.
 */
function buildDemoCode(intro) {
	const data = JSON.parse(
		fs.readFileSync(path.join(ROOT, 'playground/demo-content.json'), 'utf8')
	);
	delete data.$comment;

	const json = JSON.stringify(data);
	if (/^JSON;?$/mu.test(json)) {
		throw new Error('demo-content.json would end the PHP nowdoc early.');
	}

	const script = fs
		.readFileSync(path.join(ROOT, 'playground/demo-content.php'), 'utf8')
		.replace(/^<\?php\n/u, '');

	return [
		'<?php',
		'// Generated by scripts/build-playground-blueprints.js from playground/demo-content.{json,php}.',
		`$borges_demo_intro = ${phpSingleQuoted(intro)};`,
		`$borges_demo_json = <<<'JSON'`,
		json,
		'JSON;',
		script,
	].join('\n');
}

/**
 * Each demo blueprint with its demo step rebuilt.
 *
 * @return {Array<{file: string, current: string, expected: string}>} Blueprints.
 */
function buildBlueprints() {
	return DEMO_BLUEPRINTS.map(({ file, intro }) => {
		const absolute = path.join(ROOT, file);
		const current = fs.readFileSync(absolute, 'utf8');
		const blueprint = JSON.parse(current);
		const steps = blueprint.steps.filter((step) => step.step !== 'runPHP');

		steps.push({ step: 'runPHP', code: buildDemoCode(intro) });
		blueprint.steps = steps;

		return {
			file,
			current,
			expected: `${JSON.stringify(blueprint, null, '\t')}\n`,
		};
	});
}

if (require.main === module) {
	const check = process.argv.includes('--check');
	const stale = [];

	for (const { file, current, expected } of buildBlueprints()) {
		if (current === expected) {
			continue;
		}

		if (check) {
			stale.push(file);
		} else {
			fs.writeFileSync(path.join(ROOT, file), expected);
			process.stdout.write(`updated ${file}\n`);
		}
	}

	if (stale.length) {
		process.stderr.write(
			`Stale Playground blueprints (run npm run playground:build): ${stale.join(
				', '
			)}\n`
		);
		process.exit(1);
	}
}

module.exports = { buildBlueprints, DEMO_BLUEPRINTS };
